-- DDL for the scheduled-task ("chrontask") subsystem of the fantasy_sports schema.
--
-- Depends on schema.sql having already created "fantasy_sports"."dim_league",
-- which sched_task references. Run this after schema.sql; it is independent of
-- rumors.sql and either order works between the two.
--
--   Task kinds : dim_task_kind  (seeded by sql/dml/insert_dim_task_kind.sql)
--   Live state : sched_task     (mutable -- see the note below)
--
-- WHY NOT fact_: everything else at this grain in the schema is an append-only
-- event, and a scheduled task is not one. It is a *definition* plus live state:
-- next_fire_at moves every time it fires, status changes when somebody cancels
-- it. Calling it fact_scheduled_task would put mutable rows behind a name that
-- promises they never change. The append-only companion -- one row per firing,
-- fact_task_fire -- is the natural next table if the firing history ever needs
-- auditing beyond the last_fired_at/fire_count counters kept here.
--
-- GRANTS: 04_grant_privileges.sql gives fantasy_sports DML to `moderator` only
-- (power_user gets INSERT/UPDATE on public and unmodeled_data, not here), and
-- ALTER DEFAULT PRIVILEGES only covers tables created by the role that ran it.
-- The bot needs SELECT, INSERT and UPDATE on sched_task -- it inserts a task and
-- updates next_fire_at on every firing. Cancelling is an UPDATE to status, not a
-- delete, so the row keeps its history; DELETE is granted for pruning. The grants
-- at the bottom of this file are explicit for that reason; check them against
-- whatever role the bot actually connects as (`pylot` at the time of writing).

-- Drop child-first so foreign keys never block a rebuild.
DROP TABLE IF EXISTS "fantasy_sports"."sched_task";
DROP TABLE IF EXISTS "fantasy_sports"."dim_task_kind";

-- ---------------------------------------------------------------------------
-- Task kinds
-- ---------------------------------------------------------------------------

-- What a scheduled task *does* when it fires. Deliberately keyed on the name
-- rather than on a surrogate int, unlike the rumor dimensions: the bot has a
-- handler registry keyed on this same string, so a surrogate would mean every
-- insert first reading the dimension to translate a name it already has.
--
-- A new kind of chrontask is therefore one row here plus one handler in the
-- bot -- no DDL, which matters because the bot's own role cannot run any.
CREATE TABLE "fantasy_sports"."dim_task_kind" (
  "task_kind" varchar NOT NULL,
  "task_kind_description" varchar,
  PRIMARY KEY ("task_kind")
);

-- ---------------------------------------------------------------------------
-- Scheduled tasks
-- ---------------------------------------------------------------------------

-- One row per live scheduled task.
--
-- Discord ids are stored as opaque **surrogate bigints**, never real ones --
-- the same rule dim_manager.discord_id and dim_league.discord_server_id follow.
-- The map from surrogate back to the real id lives only in the bot, in
-- resources/anon/discord_ids.json (see wojbot/core/discord_anon.py). Surrogates
-- are 62-bit, hence bigint rather than int, and channel and role ids get their
-- own category namespaces there.
--
-- The three scopes decide who a firing reaches, and the CHECK constraints below
-- are what stop a row from claiming a reach it has no business having:
--
--   'user'    -- delivered to the owner's DM. Never has a channel; may still
--                record the guild it was set from, which is where its timezone
--                and its league came from.
--   'channel' -- posted to channel_id, and may tag the owner. Anyone may set one.
--   'server'  -- posted to channel_id and may tag *other* people (mention_ids).
--                Only a privileged user in that server may set one, which the
--                bot enforces at the command; the constraint here is only that
--                nothing else may carry mentions.
--
-- schedule_kind/schedule_spec/timezone round-trip through
-- wojbot.core.schedule.parse_stored:
--
--   'once'     spec = an ISO-8601 UTC instant
--   'interval' spec = "<ISO anchor>/<period seconds>" -- anchored so that a
--              firing delivered late never pushes the ones after it
--   'cron'     spec = a five-field crontab expression, read in `timezone`
--
-- next_fire_at is always UTC and is the poller's only index. For a cron task it
-- is *recomputed* from the expression after each firing rather than advanced by
-- a fixed offset, which is what keeps a 9am task at 9am across a daylight-saving
-- change. NULL means exhausted -- a one-shot that has fired, or a calendar
-- expression with no next match -- and status stops being 'active' at the same
-- time.
CREATE TABLE "fantasy_sports"."sched_task" (
  "task_id" bigint GENERATED BY DEFAULT AS IDENTITY,
  "task_kind" varchar NOT NULL,
  "scope" varchar NOT NULL,
  -- The league this task belongs to, when it belongs to one. NULL for a
  -- personal reminder, which is nobody's league business.
  "league_id" int,
  -- Surrogate for the Discord user who set it. Not dim_manager.manager_id: a
  -- reminder is not a league act and the owner need not be a linked manager.
  "owner_id" bigint NOT NULL,
  "guild_id" bigint,
  "channel_id" bigint,
  -- Surrogates for the users and roles a 'server' task tags. Roles and users
  -- share the array; the bot renders each by looking up which it is.
  "mention_ids" bigint[] NOT NULL DEFAULT '{}',
  -- Kind-specific payload. For 'reminder': {"text": "..."}. jsonb rather than a
  -- column per kind, so a new kind of chrontask needs no DDL.
  "payload" jsonb NOT NULL DEFAULT '{}'::jsonb,
  "schedule_kind" varchar NOT NULL,
  "schedule_spec" varchar NOT NULL,
  "timezone" varchar NOT NULL DEFAULT 'UTC',
  "next_fire_at" timestamptz,
  "last_fired_at" timestamptz,
  "fire_count" int NOT NULL DEFAULT 0,
  "status" varchar NOT NULL DEFAULT 'active',
  -- Why the last firing failed, when one did. Kept so a task that has been
  -- quietly failing can say so when somebody lists it.
  "last_error" varchar,
  "created_at" timestamptz NOT NULL DEFAULT now(),
  "updated_at" timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY ("task_id"),
  CONSTRAINT "FK_sched_task_task_kind"
    FOREIGN KEY ("task_kind")
      REFERENCES "fantasy_sports"."dim_task_kind"("task_kind"),
  CONSTRAINT "FK_sched_task_league_id"
    FOREIGN KEY ("league_id")
      REFERENCES "fantasy_sports"."dim_league"("league_id"),
  CONSTRAINT "CK_sched_task_scope"
    CHECK ("scope" IN ('user', 'channel', 'server')),
  CONSTRAINT "CK_sched_task_status"
    CHECK ("status" IN ('active', 'paused', 'done', 'cancelled', 'failed')),
  CONSTRAINT "CK_sched_task_schedule_kind"
    CHECK ("schedule_kind" IN ('once', 'interval', 'cron')),
  -- Anything posted to a server has to say where. A DM task must not.
  CONSTRAINT "CK_sched_task_destination"
    CHECK (
      CASE "scope"
        WHEN 'user' THEN "channel_id" IS NULL
        ELSE "guild_id" IS NOT NULL AND "channel_id" IS NOT NULL
      END
    ),
  -- Tagging other people is the one thing that makes a 'server' task
  -- privileged. No other scope may carry mentions, whatever wrote the row.
  CONSTRAINT "CK_sched_task_mentions"
    CHECK ("scope" = 'server' OR cardinality("mention_ids") = 0),
  -- An active task that doesn't know when it fires next would be invisible to
  -- the poller and never run again.
  CONSTRAINT "CK_sched_task_next_fire"
    CHECK ("status" <> 'active' OR "next_fire_at" IS NOT NULL)
);

-- The poller's only read: "every active task due by now, soonest first". Partial
-- on status so the index holds live tasks only -- a season of fired one-shots
-- should not be in the way of a query that runs every half minute.
CREATE INDEX "IX_sched_task_due" ON "fantasy_sports"."sched_task"
  ("next_fire_at") WHERE "status" = 'active';

-- "What have I got set?" -- /remind list, and the cancel that follows it.
CREATE INDEX "IX_sched_task_owner" ON "fantasy_sports"."sched_task"
  ("owner_id", "status");

-- Everything a server's admins can see and clear down.
CREATE INDEX "IX_sched_task_guild" ON "fantasy_sports"."sched_task"
  ("guild_id", "status") WHERE "guild_id" IS NOT NULL;

-- ---------------------------------------------------------------------------
-- Grants
-- ---------------------------------------------------------------------------

-- The bot reads the dimension and owns the task rows outright. Run as the
-- schema owner (moderator); see the note at the top of this file about why the
-- default privileges do not cover this.
GRANT SELECT ON "fantasy_sports"."dim_task_kind" TO consumer;
GRANT SELECT, INSERT, UPDATE, DELETE ON "fantasy_sports"."sched_task" TO moderator;
